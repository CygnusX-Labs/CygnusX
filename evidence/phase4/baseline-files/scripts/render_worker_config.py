#!/usr/bin/env python3
"""Render Worker path settings from YAML into a shell-compatible env file.

一致性门禁（存储层优化 Phase 3）：paths.shared_data_dir 必须与根目录 .env 的
STORAGE_PATH 完全一致，否则 exit 1——历史上二者不一致时 .env 兜住了 YAML 的
错值，经 worker-compose.sh 单独启动会把 worker 挂到错误数据根（Gap 2）。
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path
from typing import Any

import yaml

REQUIRED_PATHS = {
    "shared_data_dir": "WORKER_SHARED_DATA_DIR",
    "pipeline_dir": "WORKER_PIPELINE_DIR",
}


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Render data/worker_config.yaml for Docker Compose interpolation."
    )
    parser.add_argument(
        "--config",
        type=Path,
        default=Path("data/worker_config.yaml"),
        help="Worker YAML configuration path.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("data/.worker-config.env"),
        help="Generated shell environment file path.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Validate the YAML without writing the output file.",
    )
    return parser.parse_args()


def load_paths(config_path: Path) -> dict[str, str]:
    try:
        raw_config: Any = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise ValueError(f"Worker configuration does not exist: {config_path}") from error
    except yaml.YAMLError as error:
        raise ValueError(f"Invalid YAML in {config_path}: {error}") from error

    if not isinstance(raw_config, dict) or not isinstance(raw_config.get("paths"), dict):
        raise ValueError(f"{config_path} must define a 'paths' mapping.")

    paths = raw_config["paths"]
    rendered: dict[str, str] = {}
    for yaml_key, environment_key in REQUIRED_PATHS.items():
        value = paths.get(yaml_key)
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"paths.{yaml_key} must be a non-empty absolute path.")
        path = Path(value).expanduser()
        if not path.is_absolute():
            raise ValueError(f"paths.{yaml_key} must be absolute: {value}")
        rendered[environment_key] = str(path)

    _assert_shared_data_dir_matches_storage_path(
        rendered["WORKER_SHARED_DATA_DIR"], config_path
    )

    return rendered


def _assert_shared_data_dir_matches_storage_path(
    shared_data_dir: str, config_path: Path
) -> None:
    """fail-fast：paths.shared_data_dir 必须与仓库根 .env 的 STORAGE_PATH 一致。

    仓库根 .env 缺失（如 CI 只渲染不部署）时跳过校验；二者均存在但不一致即
    报错，防止 worker 经本脚本挂到与 web 栈不同的数据根。
    """
    env_path = config_path.resolve().parent.parent / ".env"
    if not env_path.is_file():
        return
    storage_path = ""
    for line in env_path.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if stripped.startswith("STORAGE_PATH=") and not stripped.startswith("#"):
            storage_path = stripped.split("=", 1)[1].strip().strip('"').strip("'")
            break
    if not storage_path:
        return
    if shared_data_dir != storage_path:
        raise ValueError(
            f"paths.shared_data_dir ({shared_data_dir}) 与 .env STORAGE_PATH "
            f"({storage_path}) 不一致；请将 worker_config.yaml 的 shared_data_dir "
            "与 .env 同步后重试（勿手改，见 yaml 注释）。"
        )


def render_environment(values: dict[str, str], config_path: Path) -> str:
    lines = [
        "# Generated by scripts/render_worker_config.py; do not edit.",
        f"# Source: {config_path}",
    ]
    lines.extend(f"{key}={shlex.quote(value)}" for key, value in values.items())
    return "\n".join(lines) + "\n"


def main() -> int:
    args = parse_args()
    try:
        values = load_paths(args.config)
    except ValueError as error:
        print(f"error: {error}", file=sys.stderr)
        return 1

    if args.check:
        print(f"Worker configuration is valid: {args.config}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_environment(values, args.config), encoding="utf-8")
    print(f"Rendered Worker configuration: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
